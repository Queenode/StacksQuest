/**
 * @module number/formatScientific
 * Mathematical utility function for formatScientific operations
 */
export const formatScientificUtility = (a: number, b?: number): number | boolean | string => {
  if (typeof a !== 'number') return 0;
  // Stub implementation for formatScientific
  return Number.isNaN(a) ? 0 : a;
};
